import { z } from 'zod'

import { MoneySchema } from './currency.js'

/**
 * Sourcing request specification
 */
export const SourcingSpecSchema = z.object({
  description: z.string(),
  specifications: z.record(z.string()).optional(),
  certifications: z.array(z.string()).optional(),
})
export type SourcingSpec = z.infer<typeof SourcingSpecSchema>

/**
 * Quantity tier request
 */
export const QuantityTierSchema = z.object({
  quantity: z.number().int().positive(),
  priority: z.enum(['primary', 'secondary', 'fallback']),
})
export type QuantityTier = z.infer<typeof QuantityTierSchema>

/**
 * Sourcing request (user's need)
 */
export const SourcingRequestSchema = z.object({
  id: z.string(),
  tenantId: z.string(),
  createdBy: z.string(),
  spec: SourcingSpecSchema,
  quantityTiers: z.array(QuantityTierSchema),
  maxBudget: MoneySchema.optional(),
  targetDeliveryDate: z.string().datetime().optional(),
  deliveryCountry: z.string(),
  deliveryAddress: z.string().optional(),
  excludedPlatforms: z.array(z.string()).optional(),
  excludedCountries: z.array(z.string()).optional(),
  excludedSellers: z.array(z.string()).optional(),
  createdAt: z.string().datetime(),
})
export type SourcingRequest = z.infer<typeof SourcingRequestSchema>

/**
 * Sourcing plan (generated by PlannerAgent)
 */
export const SourcingPlanSchema = z.object({
  id: z.string(),
  requestId: z.string(),
  platforms: z.array(z.string()),
  queries: z.array(
    z.object({
      platform: z.string(),
      query: z.string(),
      filters: z.record(z.unknown()).optional(),
    })
  ),
  budgetAllocation: z.record(MoneySchema),
  estimatedDurationMinutes: z.number().int().positive(),
  createdAt: z.string().datetime(),
})
export type SourcingPlan = z.infer<typeof SourcingPlanSchema>

/**
 * Mission state
 */
export const MissionStateSchema = z.enum([
  'created',
  'planning',
  'sourcing',
  'enriching',
  'evaluating',
  'negotiating',
  'awaiting_decision',
  'completed',
  'cancelled',
  'failed',
])
export type MissionState = z.infer<typeof MissionStateSchema>

/**
 * Mission (orchestrates the full sourcing flow)
 */
export const MissionSchema = z.object({
  id: z.string(),
  tenantId: z.string(),
  requestId: z.string(),
  planId: z.string().optional(),
  state: MissionStateSchema,
  offersDiscovered: z.number().int().nonnegative(),
  offersNegotiated: z.number().int().nonnegative(),
  offersInGate: z.number().int().nonnegative(),
  tokensUsed: z.number().int().nonnegative(),
  tokenBudget: z.number().int().positive(),
  startedAt: z.string().datetime(),
  completedAt: z.string().datetime().optional(),
  error: z.string().optional(),
})
export type Mission = z.infer<typeof MissionSchema>
