"""Generate ``apex/db/models/generated.py`` from a migrated database (D2-05, ADR-207).

Prisma Migrate owns the DDL (ADR-201), so the SQLAlchemy mapping is derived from what the migrations actually
create: tables, columns, types, nullability, primary keys, foreign keys (with their actions), indexes and enums.
Class names come from the Prisma models (``@@map``). The output goes through ``ruff format``, so it is stable.

    uv run python -m apex.db.codegen --database-url postgresql://postgres@localhost:5432/apex
    uv run python -m apex.db.codegen --database-url ... --check   # exit 1 when the committed file differs

The integration test ``tests/db/test_models.py`` runs the check against a freshly migrated database, so a schema
change without regenerated models fails CI. CHECK constraints, triggers and RLS policies are not mapped: they
are enforced by Postgres and SQLAlchemy never creates tables.
"""

from __future__ import annotations

import argparse
import re
import subprocess
import sys
from dataclasses import dataclass
from pathlib import Path
from typing import Any

import psycopg

ORCHESTRATOR_DIR = Path(__file__).resolve().parents[3]
OUTPUT = ORCHESTRATOR_DIR / "src" / "apex" / "db" / "models" / "generated.py"
PRISMA_SCHEMA = ORCHESTRATOR_DIR.parent / "web" / "prisma" / "schema.prisma"
EXCLUDED_TABLES = {"_prisma_migrations"}

FK_ACTIONS = {"a": None, "r": "RESTRICT", "c": "CASCADE", "n": "SET NULL", "d": "SET DEFAULT"}

HEADER = '''"""SQLAlchemy mapping of the Prisma schema.

Generated by ``python -m apex.db.codegen`` from a migrated database. Do not edit by hand: change the Prisma
schema and its migration, then regenerate (ADR-207). The integration tests fail when this file is stale.
"""

# ruff: noqa: E501

from __future__ import annotations

from datetime import date, datetime
from decimal import Decimal
from enum import StrEnum
from typing import Any

from sqlalchemy import (
    CHAR,
    BigInteger,
    Boolean,
    Date,
    ForeignKey,
    ForeignKeyConstraint,
    Index,
    Integer,
    Numeric,
    String,
    Text,
    text,
)
from sqlalchemy.dialects.postgresql import ARRAY, ENUM, JSONB, TIMESTAMP
from sqlalchemy.orm import Mapped, mapped_column

from apex.db.base import Base
from apex.db.types import Vector, enum_values
'''


@dataclass(frozen=True)
class Column:
    name: str
    data_type: str
    udt: str
    nullable: bool
    length: int | None
    precision: int | None
    scale: int | None
    datetime_precision: int | None = None


@dataclass(frozen=True)
class ForeignKeyInfo:
    name: str
    columns: list[str]
    ref_table: str
    ref_columns: list[str]
    on_update: str | None
    on_delete: str | None


@dataclass(frozen=True)
class IndexInfo:
    name: str
    columns: list[str]
    unique: bool
    where: str | None


@dataclass
class Catalog:
    enums: dict[str, list[str]]
    columns: dict[str, list[Column]]
    primary_keys: dict[str, list[str]]
    foreign_keys: dict[str, list[ForeignKeyInfo]]
    indexes: dict[str, list[IndexInfo]]


def load_catalog(conn: psycopg.Connection) -> Catalog:
    enums: dict[str, list[str]] = {}
    for name, labels in conn.execute(
        "SELECT t.typname, array_agg(e.enumlabel::text ORDER BY e.enumsortorder) FROM pg_enum e "
        "JOIN pg_type t ON t.oid = e.enumtypid WHERE t.typnamespace = 'public'::regnamespace "
        "GROUP BY t.typname ORDER BY t.typname"
    ):
        enums[name] = list(labels)

    columns: dict[str, list[Column]] = {}
    for row in conn.execute(
        "SELECT c.table_name, c.column_name, c.data_type, c.udt_name, c.is_nullable = 'YES', "
        "c.character_maximum_length, c.numeric_precision, c.numeric_scale, c.datetime_precision "
        "FROM information_schema.columns c JOIN information_schema.tables t "
        "ON t.table_schema = c.table_schema AND t.table_name = c.table_name AND t.table_type = 'BASE TABLE' "
        "WHERE c.table_schema = 'public' ORDER BY c.table_name, c.ordinal_position"
    ):
        table, *rest = row
        if table not in EXCLUDED_TABLES:
            columns.setdefault(table, []).append(Column(*rest))

    def keyed(sql: str) -> dict[str, list[tuple[Any, ...]]]:
        out: dict[str, list[tuple[Any, ...]]] = {}
        for table, *rest in conn.execute(sql):
            if table not in EXCLUDED_TABLES:
                out.setdefault(table, []).append(tuple(rest))
        return out

    attnames = (
        "array(SELECT a.attname::text FROM unnest({keys}) WITH ORDINALITY k(n, i) "
        "JOIN pg_attribute a ON a.attrelid = {rel} AND a.attnum = k.n ORDER BY k.i)"
    )
    primary_keys = {
        table: list(rows[0][0])
        for table, rows in keyed(
            "SELECT cl.relname, "
            + attnames.format(keys="con.conkey", rel="con.conrelid")
            + " FROM pg_constraint con JOIN pg_class cl ON cl.oid = con.conrelid "
            "WHERE con.contype = 'p' AND con.connamespace = 'public'::regnamespace"
        ).items()
    }
    foreign_keys = {
        table: [
            ForeignKeyInfo(
                name=str(name),
                columns=list(cols),
                ref_table=str(ref_table),
                ref_columns=list(ref_cols),
                on_update=FK_ACTIONS[str(upd)],
                on_delete=FK_ACTIONS[str(dele)],
            )
            for name, cols, ref_table, ref_cols, upd, dele in rows
        ]
        for table, rows in keyed(
            "SELECT cl.relname, con.conname, "
            + attnames.format(keys="con.conkey", rel="con.conrelid")
            + ", pcl.relname, "
            + attnames.format(keys="con.confkey", rel="con.confrelid")
            + ", con.confupdtype, con.confdeltype FROM pg_constraint con "
            "JOIN pg_class cl ON cl.oid = con.conrelid JOIN pg_class pcl ON pcl.oid = con.confrelid "
            "WHERE con.contype = 'f' AND con.connamespace = 'public'::regnamespace ORDER BY con.conname"
        ).items()
    }
    indexes = {
        table: [
            IndexInfo(name=str(name), columns=list(cols), unique=bool(unique), where=where)
            for name, cols, unique, where, expressions in rows
            if not _reject_expression_index(str(name), bool(expressions))
        ]
        for table, rows in keyed(
            "SELECT cl.relname, ic.relname, "
            + attnames.format(keys="i.indkey::int2[]", rel="i.indrelid")
            + ", i.indisunique, pg_get_expr(i.indpred, i.indrelid), i.indexprs IS NOT NULL "
            "FROM pg_index i JOIN pg_class cl ON cl.oid = i.indrelid JOIN pg_class ic ON ic.oid = i.indexrelid "
            "WHERE cl.relnamespace = 'public'::regnamespace AND NOT i.indisprimary ORDER BY ic.relname"
        ).items()
    }
    unique_constraints = conn.execute(
        "SELECT count(*) FROM pg_constraint WHERE contype = 'u' AND connamespace = 'public'::regnamespace"
    ).fetchone()
    if unique_constraints != (0,):
        raise SystemExit(
            "unique constraints are not supported by the generator yet; Prisma emits unique indexes"
        )
    return Catalog(enums, columns, primary_keys, foreign_keys, indexes)


def _reject_expression_index(name: str, has_expressions: bool) -> bool:
    if has_expressions:
        raise SystemExit(f"expression index {name} is not supported by the generator yet")
    return False


def prisma_model_names(schema: str) -> dict[str, str]:
    """Table name -> Prisma model name, from the ``@@map`` attribute of each model."""
    names: dict[str, str] = {}
    for match in re.finditer(r"^model (\w+) \{(.*?)^\}", schema, re.MULTILINE | re.DOTALL):
        model, body = match.group(1), match.group(2)
        mapped = re.search(r'@@map\("([^"]+)"\)', body)
        names[mapped.group(1) if mapped else model] = model
    return names


def _member(label: str) -> str:
    name = re.sub(r"\W", "_", label).upper()
    return f"_{name}" if name[0].isdigit() else name


def _types(column: Column, enums: dict[str, list[str]]) -> tuple[str, str]:
    """(python annotation, SQLAlchemy type expression) for a column."""
    if column.data_type == "ARRAY":
        element = Column(column.name, "", column.udt.removeprefix("_"), False, None, None, None)
        element_type = element.udt
        data_type = "USER-DEFINED" if element_type in enums else _scalar_data_type(element_type)
        py, sa = _types(
            Column(column.name, data_type, element_type, False, None, None, None), enums
        )
        return f"list[{py}]", f"ARRAY({sa})"
    if column.data_type == "USER-DEFINED":
        if column.udt == "vector":
            return "list[float]", "Vector()"
        if column.udt in enums:
            return column.udt, (
                f'ENUM({column.udt}, name="{column.udt}", create_type=False, values_callable=enum_values)'
            )
    if column.data_type == "text":
        return "str", "Text"
    if column.data_type == "character varying":
        return "str", f"String({column.length})" if column.length else "String"
    if column.data_type == "character":
        return "str", f"CHAR({column.length})"
    if column.data_type == "integer":
        return "int", "Integer"
    if column.data_type == "bigint":
        return "int", "BigInteger"
    if column.data_type == "numeric":
        args = f"{column.precision}, {column.scale}" if column.precision is not None else ""
        return "Decimal", f"Numeric({args})"
    if column.data_type == "boolean":
        return "bool", "Boolean"
    if column.data_type == "timestamp with time zone":
        precision = (
            f", precision={column.datetime_precision}"
            if column.datetime_precision is not None
            else ""
        )
        return "datetime", f"TIMESTAMP(timezone=True{precision})"
    if column.data_type == "date":
        return "date", "Date"
    if column.data_type == "jsonb":
        return "Any", "JSONB"
    raise SystemExit(f"no mapping for column {column.name} ({column.data_type}/{column.udt})")


def _scalar_data_type(udt: str) -> str:
    return {
        "text": "text",
        "varchar": "character varying",
        "int4": "integer",
        "int8": "bigint",
        "numeric": "numeric",
        "bool": "boolean",
        "timestamptz": "timestamp with time zone",
        "date": "date",
        "jsonb": "jsonb",
    }.get(udt, udt)


def _fk_kwargs(fk: ForeignKeyInfo) -> str:
    parts = [f'name="{fk.name}"']
    if fk.on_delete:
        parts.append(f'ondelete="{fk.on_delete}"')
    if fk.on_update:
        parts.append(f'onupdate="{fk.on_update}"')
    return ", ".join(parts)


def render(catalog: Catalog, model_names: dict[str, str]) -> str:
    out = [HEADER]
    for enum_name, labels in catalog.enums.items():
        out.append(f"\n\nclass {enum_name}(StrEnum):")
        out.extend(f'    {_member(label)} = "{label}"' for label in labels)

    classes: list[str] = []
    for table in sorted(catalog.columns):
        if table not in model_names:
            raise SystemExit(f"table {table} has no Prisma model with @@map")
        class_name = model_names[table]
        classes.append(class_name)
        fks = catalog.foreign_keys.get(table, [])
        inline = {fk.columns[0]: fk for fk in fks if len(fk.columns) == 1}
        args: list[str] = []
        for fk in fks:
            if len(fk.columns) > 1:
                args.append(
                    f"ForeignKeyConstraint({fk.columns!r}, "
                    f"{[f'{fk.ref_table}.{c}' for c in fk.ref_columns]!r}, {_fk_kwargs(fk)})"
                )
        for index in catalog.indexes.get(table, []):
            cols = ", ".join(f'"{c}"' for c in index.columns)
            extra = ", unique=True" if index.unique else ""
            if index.where:
                extra += f", postgresql_where=text({index.where!r})"
            args.append(f'Index("{index.name}", {cols}{extra})')

        out.append(f"\n\nclass {class_name}(Base):")
        out.append(f'    __tablename__ = "{table}"')
        if args:
            out.append("    __table_args__ = (" + ", ".join(args) + ",)")
        out.append("")
        primary_key = catalog.primary_keys.get(table, [])
        for column in catalog.columns[table]:
            py, sa = _types(column, catalog.enums)
            parts = [sa]
            if column.name in inline:
                fk = inline[column.name]
                parts.append(f'ForeignKey("{fk.ref_table}.{fk.ref_columns[0]}", {_fk_kwargs(fk)})')
            if column.name in primary_key:
                parts.append("primary_key=True")
            annotation = f"{py} | None" if column.nullable else py
            out.append(
                f"    {column.name}: Mapped[{annotation}] = mapped_column({', '.join(parts)})"
            )

    exported = sorted([*catalog.enums, *classes])
    out.append("\n\n__all__ = [" + ", ".join(f'"{name}"' for name in exported) + "]\n")
    return _format("\n".join(out))


def _format(source: str) -> str:
    result = subprocess.run(
        [sys.executable, "-m", "ruff", "format", "--stdin-filename", str(OUTPUT), "-"],
        input=source,
        capture_output=True,
        text=True,
        cwd=ORCHESTRATOR_DIR,
        check=False,
    )
    if result.returncode != 0:
        raise SystemExit(f"ruff format failed:\n{result.stderr}")
    return result.stdout


def generate(database_url: str) -> str:
    with psycopg.connect(database_url) as conn:
        catalog = load_catalog(conn)
    return render(catalog, prisma_model_names(PRISMA_SCHEMA.read_text(encoding="utf-8")))


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0] if __doc__ else None)
    parser.add_argument(
        "--database-url", required=True, help="a migrated database (postgresql://...)"
    )
    parser.add_argument(
        "--check", action="store_true", help="fail when the committed file is stale"
    )
    args = parser.parse_args(argv)
    source = generate(args.database_url)
    if args.check:
        if OUTPUT.read_text(encoding="utf-8") != source:
            print(
                f"{OUTPUT} is stale: run python -m apex.db.codegen --database-url ...",
                file=sys.stderr,
            )
            return 1
        return 0
    OUTPUT.write_text(source, encoding="utf-8")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
